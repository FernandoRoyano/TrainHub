// Paginado (PostgREST corta a 1000)
async function fetchUntranslated() {
  const rows = [];
  const pageSize = 1000;
  for (let from = 0; ; from += pageSize) {
    const { data, error } = await supabase
      .from("exercises")
      .select("id, name, name_es")
      .is("trainer_id", null)
      .is("archived_at", null)
      .order("name")
      .range(from, from + pageSize - 1);
    if (error) throw error;
    rows.push(...(data ?? []));
    if (!data || data.length < pageSize) break;
  }
  return rows.filter((e) => !e.name_es || e.name_es.trim() === "" || e.name_es === e.name);
}

const rows = await fetchUntranslated();
let fromMap = 0;
let fallback = 0;
const updates = [];
for (const row of rows) {
  const translated = TRANSLATIONS[row.name];
  const name_es = translated ?? row.name; // sin match = ya está en español
  if (name_es === row.name_es) continue; // sin cambio real
  if (translated) fromMap++;
  else fallback++;
  updates.push({ id: row.id, name: row.name, name_es, name_es_prev: row.name_es });
}

console.log(`Sin traducir: ${rows.length}`);
console.log(`Con traducción del mapa: ${fromMap} | fallback name_es=name: ${fallback}`);

if (!APPLY) {
  console.log("\nDRY-RUN (usa --apply para escribir). Muestra:");
  for (const u of updates.filter((x) => TRANSLATIONS[x.name]).slice(0, 15)) {
    console.log(`  "${u.name}" → "${u.name_es}"`);
  }
  process.exit(0);
}

// Rollback antes de tocar nada
const rollbackFile = `translations-rollback-${Date.now()}.json`;
writeFileSync(
  rollbackFile,
  JSON.stringify(updates.map(({ id, name_es_prev }) => ({ id, name_es_prev })), null, 2)
);
console.log(`Rollback guardado en ${rollbackFile}`);

let done = 0;
let errors = 0;
for (const u of updates) {
  const { error } = await supabase.from("exercises").update({ name_es: u.name_es }).eq("id", u.id);
  if (error) {
    errors++;
    console.error(`ERROR ${u.name}: ${error.message}`);
  } else {
    done++;
  }
  if (done % 100 === 0) console.log(`  ${done}/${updates.length}…`);
}
console.log(`Aplicado: ${done} actualizados, ${errors} errores.`);
